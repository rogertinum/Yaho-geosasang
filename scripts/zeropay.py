def phone(raw):
    """'0556871234' -> '055-687-1234', '01012345678' -> '010-1234-5678', '15770711' -> '1577-0711'.
    비었거나 0만 있는 번호는 None. 제로페이에 등록된 그대로(개인 휴대폰 포함) 보여 준다."""
    d = re.sub(r"\D", "", raw or "")
    body = re.sub(r"^0(?:2|\d\d)", "", d)
    if len(d) < 7 or len(set(body)) <= 1:  # '0', '0200000000', '0222222222' 같은 빈칸 메우기 번호
        return None
    if d.startswith("050") and len(d) >= 11:  # 0507-1438-2483 같은 안심번호
        return f"{d[:4]}-{d[4:-4]}-{d[-4:]}"
    m = re.fullmatch(r"(?:02|0)?(1[5-9]\d{2})(\d{4})", d)  # 1577-0711 같은 대표번호 (앞에 02가 붙어 있기도 함)
    if m:
        return f"{m.group(1)}-{m.group(2)}"
    if d.startswith("02"):
        return f"02-{d[2:-4]}-{d[-4:]}"
    if d.startswith("0") and len(d) >= 9:
        return f"{d[:3]}-{d[3:-4]}-{d[-4:]}"
    if len(d) in (7, 8):  # 지역번호 없이 적힌 번호는 거제(055)로 본다
        return f"055-{d[:-4]}-{d[-4:]}"
    return d


def shared_phones(rows, limit=4):
    """여러 가게(limit곳 이상)가 같이 쓰는 번호는 본사 대표번호라 가게 전화로 보여 주지 않는다."""
    names = {}
    for r in rows:
        p = phone(r["tel"])
        if p:
            names.setdefault(p, set()).add(r["name"])
    return {p for p, n in names.items() if len(n) >= limit}


def area_of(addr, areas):
    """주소에서 읍면동을 찾는다: '… 거제면 …' 또는 '…(고현동)'. areas(지류 목록의 읍면동)에 있는 이름만."""
    m = re.search(r"거제시\s+(\S+[읍면])\s", addr or "")
    if m and m.group(1) in areas:
        return m.group(1)
    for d in re.findall(r"\(\s*([^,()\s]+동)", addr or ""):
        if d in areas:
            return d
    return None
